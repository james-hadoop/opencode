def alter_table():
    """修改表结构，添加国际分类字段"""
    conn = get_db_connection()
    try:
        with conn.cursor() as cursor:
            # 添加 GICS 分类字段
            cursor.execute("""
            ALTER TABLE app.t_app_stock_business_inc_d 
            ADD COLUMN gics_sector_code VARCHAR(10) COMMENT 'GICS行业组代码' AFTER business,
            ADD COLUMN gics_industry_code VARCHAR(10) COMMENT 'GICS行业代码',
            ADD COLUMN gics_subindustry_code VARCHAR(10) COMMENT 'GICS子行业代码',
            ADD COLUMN gics_sector_name VARCHAR(50) COMMENT 'GICS行业组名称',
            ADD COLUMN gics_industry_name VARCHAR(50) COMMENT 'GICS行业名称'
            """)
            
            # 添加 ICB 分类字段
            cursor.execute("""
            ALTER TABLE app.t_app_stock_business_inc_d 
            ADD COLUMN icb_sector_code VARCHAR(10) COMMENT 'ICB行业部门代码' AFTER gics_industry_name,
            ADD COLUMN icb_industry_code VARCHAR(10) COMMENT 'ICB行业代码',
            ADD COLUMN icb_super_sector_code VARCHAR(10) COMMENT 'ICB超级行业代码',
            ADD COLUMN icb_sector_name VARCHAR(50) COMMENT 'ICB行业部门名称',
            ADD COLUMN icb_industry_name VARCHAR(50) COMMENT 'ICB行业名称'
            """)
            
            conn.commit()
            print("✓ 表结构已更新，添加了 GICS 和 ICB 分类字段")
    finally:
        conn.close()


def get_classification(industry):
    """获取国际分类"""
    if not industry:
        return None, None
    
    # 精确匹配
    if industry in GICS_MAP:
        gics = GICS_MAP[industry]
        icb = ICB_MAP.get(industry, ('', '', '', '', ''))
        return gics, icb
    
    # 模糊匹配
    for key in GICS_MAP:
        if key in industry or industry in key:
            gics = GICS_MAP[key]
            icb = ICB_MAP.get(key, ('', '', '', '', ''))
            return gics, icb
    
    return None, None


def update_classifications():
    """更新所有股票的国际分类"""
    conn = get_db_connection()
    try:
        with conn.cursor() as cursor:
            # 获取所有股票
            cursor.execute("SELECT id, ts_code, industry FROM app.t_app_stock_business_inc_d")
            stocks = cursor.fetchall()
            
            updated = 0
            for stock in stocks:
                gics, icb = get_classification(stock['industry'])
                
                if gics:
                    cursor.execute("""
                    UPDATE app.t_app_stock_business_inc_d SET
                        gics_sector_code = %s,
                        gics_industry_code = %s,
                        gics_subindustry_code = %s,
                        gics_sector_name = %s,
                        gics_industry_name = %s,
                        icb_sector_code = %s,
                        icb_industry_code = %s,
                        icb_super_sector_code = %s,
                        icb_sector_name = %s,
                        icb_industry_name = %s
                    WHERE id = %s
                    """, (
                        gics[0], gics[1], gics[2], gics[3], gics[4],
                        icb[0], icb[1], icb[2], icb[3], icb[4],
                        stock['id']
                    ))
                    updated += 1
            
            conn.commit()
            print(f"✓ 已更新 {updated} 只股票的国际分类")
    finally:
        conn.close()


